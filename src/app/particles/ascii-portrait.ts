const backgroundLimits: Readonly<Record<number, number>> = {
  0: 0,
  1: 0,
  15: 70,
  16: 70,
  41: 72,
  42: 72
};

const normalizedPortrait = portraitLines.map((line, row) => {
  const contentLimit = backgroundLimits[row] ?? PORTRAIT_WIDTH;
  return line.slice(0, contentLimit).padEnd(PORTRAIT_WIDTH, ' ');
});

function replaceSegment(line: string, start: number, replacement: string): string {
  return `${line.slice(0, start)}${replacement}${line.slice(start + replacement.length)}`;
}

function closeEyes(line: string): string {
  const withLeftEyeClosed = replaceSegment(line, 34, '--=--');
  return replaceSegment(withLeftEyeClosed, 53, '--=--');
}

function createFrame(blinking = false): string {
  return normalizedPortrait
    .map((line, row) => {
      return blinking && row === 21 ? closeEyes(line) : line;
    })
    .join('\n');
}

export const ASCII_PORTRAIT_FRAMES = [
  createFrame(),
  createFrame(true)
] as const;

